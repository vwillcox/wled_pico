constexpr int kFontHeaderSize = 12;
constexpr int kFontBytesPerGlyph = 3;  // ceil(kFontGlyphWidth * kFontGlyphHeight / 8)

// True if glyph `c`'s pixel at (col, row) (0-indexed, row 0 = top) is lit.
// `c` outside [kFontFirstChar, kFontLastChar] renders as blank (all-false)
// rather than out-of-bounds.
inline bool font_pixel(char c, int col, int row) {
  if (c < kFontFirstChar || c > kFontLastChar) return false;
  int glyph_index = c - kFontFirstChar;
  const uint8_t *glyph = kFontTomThumb + kFontHeaderSize + glyph_index * kFontBytesPerGlyph;
  int bit_index = row * kFontGlyphWidth + col;
  int byte_index = bit_index / 8;
  int bit_in_byte = 7 - (bit_index % 8);
  return (glyph[byte_index] >> bit_in_byte) & 1;
}

